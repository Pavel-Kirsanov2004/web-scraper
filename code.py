# -------- ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ --------
DEFAULT_APP_ID  = 389801252   # Instagram (на случай, если пользователь передумает)
DEFAULT_COUNTRY = "us"
MAX_PAGES       = 10          # Apple ограничивает глубину фида 10 страницами
# --------------------------------------


def ask_app_id() -> int:
    """
    Интерактивно запрашивает у пользователя числовой ID приложения.
    Возвращает int или значение по умолчанию, если ввод пуст/некорректен.
    """
    print("Введите числовой ID приложения из App Store.")
    print("Например, для Instagram это 389801252.")
    print(f"Оставьте поле пустым и нажмите Enter, чтобы использовать значение по умолчанию ({DEFAULT_APP_ID}).\n")

    while True:
        raw = input("APP_ID: ").strip()

        # Пустой ввод → значение по умолчанию
        if not raw:
            print(f"[INFO] Использую ID по умолчанию: {DEFAULT_APP_ID}\n")
            return DEFAULT_APP_ID

        # Пользователь мог вставить целый URL — вытащим из него цифры
        # Примеры: https://apps.apple.com/us/app/instagram/id389801252
        #          id389801252
        if not raw.isdigit():
            match = re.search(r"id(\d+)", raw) or re.search(r"(\d{6,})", raw)
            if match:
                extracted = int(match.group(1))
                print(f"[INFO] Из ввода извлечён ID: {extracted}\n")
                return extracted

            print("[ERROR] ID должен состоять только из цифр (минимум 6). Попробуйте ещё раз.\n")
            continue

        # Минимальная валидация: App Store ID — обычно 6–12 цифр
        if len(raw) < 6:
            print("[ERROR] Слишком короткий ID. Похоже на опечатку. Попробуйте ещё раз.\n")
            continue

        return int(raw)


def ask_country() -> str:
    """
    Интерактивно запрашивает код страны (двухбуквенный, ISO 3166-1 alpha-2).
    """
    print("Введите код страны (например, us, ru, gb, de).")
    print(f"Оставьте поле пустым и нажмите Enter, чтобы использовать '{DEFAULT_COUNTRY}'.\n")

    while True:
        raw = input("COUNTRY: ").strip().lower()

        if not raw:
            print(f"[INFO] Использую страну по умолчанию: {DEFAULT_COUNTRY}\n")
            return DEFAULT_COUNTRY

        # Код страны — ровно 2 латинские буквы
        if not re.fullmatch(r"[a-z]{2}", raw):
            print("[ERROR] Код страны должен состоять из двух латинских букв (например, ru). Попробуйте ещё раз.\n")
            continue

        return raw


def fetch_reviews(app_id: int, country: str = "us", max_pages: int = 10):
    """
    Собирает отзывы о приложении из RSS-фида Apple App Store.
    """
    reviews = []
    headers = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 (KHTML, like Gecko) "
            "Chrome/120.0 Safari/537.36"
        )
    }

    for page in range(1, max_pages + 1):
        url = (
            f"https://itunes.apple.com/{country}/rss/customerreviews/"
            f"page={page}/id={app_id}/sortby=mostrecent/json"
        )
        print(f"[INFO] Запрашиваю страницу {page}: {url}")

        try:
            response = requests.get(url, headers=headers, timeout=15)
        except requests.RequestException as e:
            print(f"[ERROR] Ошибка сети на странице {page}: {e}")
            break

        if response.status_code != 200:
            print(f"[ERROR] Статус {response.status_code} на странице {page}. Останавливаюсь.")
            break

        try:
            data = response.json()
        except ValueError:
            print(f"[WARN] Страница {page}: не удалось распарсить JSON. Останавливаюсь.")
            break

        feed = data.get("feed", {})
        entries = feed.get("entry", [])

        # Если отзыв один — Apple вернёт dict, а не list
        if isinstance(entries, dict):
            entries = [entries]

        # Убираем служебную запись о самом приложении (у неё нет im:rating)
        entries = [e for e in entries if "im:rating" in e]

        if not entries:
            print(f"[INFO] Страница {page} пуста. Завершаю сбор.")
            break

        for entry in entries:
            reviews.append({
                "author":  entry.get("author", {}).get("name", {}).get("label", ""),
                "title":   entry.get("title", {}).get("label", ""),
                "content": entry.get("content", {}).get("label", ""),
                "rating":  entry.get("im:rating", {}).get("label", ""),
                "version": entry.get("im:version", {}).get("label", ""),
                "updated": entry.get("updated", {}).get("label", ""),
            })

        time.sleep(0.7)

    return reviews


